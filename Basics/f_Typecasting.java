package Basics;
import java.util.*;

public class f_Typecasting {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        
        double a = sc.nextDouble();
        System.out.println(a);
        
        int b = (int) a;
        System.out.println(b);

        long c = (long)a;
        System.out.println(c);
    }
    
}
